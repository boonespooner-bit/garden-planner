function springCutback(what: string, height: string): CareTask {
  return {
    id: "spring-cutback",
    type: "prune",
    title: "Cut back last year's growth",
    timing: before("lastFrost", -4, 0),
    why: `Old ${what} stems shelter overwintering beneficial insects and protect the crown in winter. Cutting them in late winter clears the way for fresh growth.`,
    steps: [
      `Cut all of last year's dead stems down to ${height}.`,
      "Do it before new shoots get tall, so you don't snip them by accident.",
      "Leave the cut stems loosely on the ground or in a brush pile for a few weeks so emerging bees can escape, then compost them.",
    ],
    tools: ["Bypass pruners or hedge shears"],
  };
}

function divide(timing: "spring" | "fall", why: string): CareTask {
  return {
    id: "divide",
    type: "plant-care",
    title: "Divide crowded clumps (every 3–4 years)",
    timing: timing === "spring" ? before("lastFrost", -1, 3) : before("firstFrost", -6, -3),
    why,
    steps: [
      "Only needed if the clump is crowded, flowering less, or dead in the center.",
      "Dig around the clump and lift it with a fork.",
      "Split it into fist-sized pieces with a sharp spade or knife, each with roots and shoots.",
      "Replant at the same depth, water well, and share the extras.",
    ],
    tools: ["Spade", "Garden fork"],
  };
}

function perennialFeed(products: Product[] = [P.balancedOrganic, P.compost]): CareTask {
  return {
    id: "feed",
    type: "fertilize",
    title: "Spring feeding",
    timing: before("lastFrost", 0, 3),
    why: "A single feeding as new shoots emerge is enough for most perennials. Overfeeding makes them floppy.",
    steps: ["Scatter a balanced slow-release or organic fertilizer around the plant, or top-dress with 1 in (2–3 cm) of compost, then water."],
    products,
  };
}

function deadhead(note: string, start = 8): CareTask {
  return {
    id: "deadhead",
    type: "prune",
    title: "Deadhead for more flowers",
    timing: before("lastFrost", start, start + 2),
    repeat: { everyWeeks: 3, times: 3 },
    why: "Removing faded flowers before they set seed encourages new blooms.",
    steps: [note],
  };
}

