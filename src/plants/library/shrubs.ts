/** "Prune right after flowering" task for shrubs that bloom on last year's wood. */
function pruneAfterBloom(timing: Timing, extra: string[] = [], tools = ["Bypass pruners", "Loppers"]): CareTask {
  return {
    id: "after-bloom-prune",
    type: "prune",
    title: "Prune right after flowering",
    timing,
    why: "This shrub sets next year's flower buds over the summer. Pruning within a few weeks after the flowers fade gives the most blooms next year. Prune later and you cut off the buds.",
    steps: [
      "Wait until the last flowers have faded.",
      "Remove dead, damaged and crossing branches first.",
      "Renewal-prune: cut one-third of the oldest, thickest stems right down to the ground. Over three years this replaces the whole shrub with vigorous young wood.",
      "Shorten overly long stems to an outward-facing bud or side branch to shape the shrub. Avoid shearing it into a ball.",
      ...extra,
    ],
    tools,
  };
}

