/** Nut-tree pollination note, shared by the many nut trees that need a partner. */
const partner = (detail: string) => `Plant at least two compatible varieties within about 50 ft (15 m) for pollination: ${detail}`;

function sanitation(what: string): CareTask {
  return {
    id: "sanitation",
    type: "plant-care",
    title: "Clean up old nuts and husks",
    timing: before("lastFrost", -10, -4),
    why: `${what} overwinter in nuts left on the tree and ground. Removing them is the most effective non-spray control.`,
    steps: [
      "Knock or pull off any shriveled 'mummy' nuts still hanging in the tree.",
      "Rake up fallen nuts, husks and debris under the canopy.",
      "Bag or destroy them. Don't compost unless your pile gets hot.",
    ],
    tools: ["Rake", "Pole pruner or long stick"],
  };
}

function nutHarvestDrying(steps: string[]): string[] {
  return [
    ...steps,
    "Dry nuts in a single layer in a warm, airy, shaded spot (or mesh bags hung indoors) for 1–3 weeks until the kernels snap rather than bend.",
    "Store dried nuts in the shell in a cool, dry place, or shelled in the fridge or freezer. Shelled nuts go rancid at room temperature.",
  ];
}

